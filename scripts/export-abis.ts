/**
 * Export contract ABIs from Foundry artifacts into packages/core/src/abis.ts (typed `as const` for viem).
 *   pnpm build:contracts && pnpm abis
 */
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const root = new URL("..", import.meta.url).pathname;
const contracts = [
  "PerpetuaVault",
  "RiskGate",
  "AgentWallet",
  "HarvestRouter",
  "ComputeTreasury",
  "AgentRegistry",
  "MockERC20",
  "MockCCIPRouter",
  "MockLending",
];

let out = "// AUTO-GENERATED by scripts/export-abis.ts from contracts/out. Do not edit.\n\n";
for (const c of contracts) {
  const art = JSON.parse(readFileSync(join(root, "contracts/out", `${c}.sol`, `${c}.json`), "utf8"));
  out += `export const ${c[0].toLowerCase()}${c.slice(1)}Abi = ${JSON.stringify(art.abi, null, 2)} as const;\n\n`;
}
writeFileSync(join(root, "packages/core/src/abis.ts"), out);
console.log(`wrote ${contracts.length} ABIs to packages/core/src/abis.ts`);
